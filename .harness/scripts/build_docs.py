#!/usr/bin/env python3
"""Build docs-site/: the whole docs/ folder as ONE self-contained HTML page (+ hosting files).

Readers need nothing installed:
  - offline: double-click docs-site/index.html (works from disk, no internet)
  - online:  connect the repo to Cloudflare Pages (or any static host) with
             build command: none, output directory: docs-site
It has navigation, search, diagrams (Mermaid) and light/dark themes.

Output (generated, committed):
    docs/backlog/index.md  backlog page (from docs/backlog/backlog.json + .harness/state/feature_list.json)
    docs-site/index.html   the documentation
    docs-site/_headers     Cloudflare Pages headers (noindex + security headers)
    docs-site/robots.txt   keeps search engines out

Usage:
    python .harness/scripts/build_docs.py           # write the backlog page and docs-site/
    python .harness/scripts/build_docs.py --check   # exit 1 if anything generated is out of date

Stdlib only. The pre-commit hook runs it automatically when docs change.

Navigation is derived from the folder structure (no config to maintain):
  - one section per top-level folder of docs/, ordered by SECTIONS below (unknown folders go last)
  - pages ordered by PAGE_ORDER, then alphabetically; sub-folders become groups (e.g. ADRs)
  - page title = first "# " heading of the file

Supported Markdown on top of GitHub-flavoured Markdown (same syntax as MkDocs Material, so the
files stay portable):
  !!! type "Title"      admonition         (types: note info tip success warning danger abstract question)
  ??? type "Title"      collapsible block  (???+ = expanded by default)
  === "Tab title"       content tabs
  ```mermaid            diagrams
"""
from __future__ import annotations

import argparse
import html
import json
import os
import re
import sys

sys.dont_write_bytecode = True  # keep the repo free of __pycache__
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import render_backlog  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DOCS = os.path.join(ROOT, "docs")
VIEWER = os.path.join(ROOT, ".harness", "docs-viewer")
OUTPUT_DIR = os.path.join(ROOT, "docs-site")

HEADERS = """# Generated by .harness/scripts/build_docs.py - Cloudflare Pages response headers.
# Internal documentation: keep it out of search engines. Restrict who can open it with
# Cloudflare Access (see docs/process/documentation-guide.md).
/*
  X-Robots-Tag: noindex, nofollow
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: no-referrer
"""
ROBOTS = "User-agent: *\nDisallow: /\n"

SECTIONS = [
    ("", "Home"),
    ("business", "Business"),
    ("backlog", "Backlog"),
    ("architecture", "Architecture"),
    ("project-context", "Project context"),
    ("process", "Ways of working"),
]
PAGE_ORDER = {
    "": ["index.md"],
    "business": ["overview.md", "user-journeys.md", "roles-and-permissions.md", "roadmap.md", "glossary.md"],
    "architecture": ["overview.md"],
    "project-context": ["PROJECT_CONTEXT.md", "discovery-questionnaire.md"],
    "process": ["definition-of-ready.md", "definition-of-done.md", "work-item-template.md", "documentation-guide.md"],
}
EXCLUDE_DIRS = {"resources", "assets"}
GROUP_TITLES = {"decisions": "Decisions (ADRs)"}

BLOCK_RE = re.compile(r'^(?P<indent> *)(?P<kind>!!!|\?\?\?\+?|===)\s*(?P<type>[\w-]+)?\s*(?:"(?P<title>[^"]*)")?\s*$')
FENCE_RE = re.compile(r"^ *(`{3,}|~{3,})")


# --------------------------------------------------------------------------- markdown preprocessing
def preprocess(md: str) -> str:
    """Turn admonitions / collapsibles / tabs into HTML wrappers that marked.js renders.

    The inner content stays Markdown: CommonMark ends an HTML block at a blank line, so the
    wrapped content (surrounded by blank lines) is parsed as Markdown.
    """
    lines = md.split("\n")
    out: list[str] = []
    i = 0
    fence: str | None = None
    while i < len(lines):
        line = lines[i]
        fm = FENCE_RE.match(line)
        if fence:
            out.append(line)
            if fm and fm.group(1)[0] == fence[0] and len(fm.group(1)) >= len(fence):
                fence = None
            i += 1
            continue
        if fm:
            fence = fm.group(1)
            out.append(line)
            i += 1
            continue
        m = BLOCK_RE.match(line)
        if not m or (m.group("kind") == "===" and m.group("title") is None):
            out.append(line)
            i += 1
            continue
        indent = len(m.group("indent"))
        body: list[str] = []
        i += 1
        while i < len(lines):
            nxt = lines[i]
            if nxt.strip() == "":
                body.append("")
            elif len(nxt) - len(nxt.lstrip(" ")) >= indent + 4:
                body.append(nxt[indent + 4:])
            else:
                break
            i += 1
        while body and body[-1] == "":
            body.pop()
        inner = preprocess("\n".join(body))
        kind, typ = m.group("kind"), (m.group("type") or "note")
        title = m.group("title")
        pad = " " * indent
        if kind == "===":
            out += [f'{pad}<div class="tabbed" data-title="{html.escape(title, quote=True)}">', "", inner, "", f"{pad}</div>", ""]
        elif kind == "!!!":
            head = f'<p class="admonition-title">{html.escape(title if title is not None else typ.capitalize())}</p>' if title != "" else ""
            out += [f'{pad}<div class="admonition {typ}">{head}<div class="admonition-body">', "", inner, "", f"{pad}</div></div>", ""]
        else:
            opened = " open" if kind.endswith("+") else ""
            summary = html.escape(title if title else typ.capitalize())
            out += [f'{pad}<details class="admonition {typ}"{opened}><summary>{summary}</summary><div class="admonition-body">',
                    "", inner, "", f"{pad}</div></details>", ""]
    return "\n".join(out)


# --------------------------------------------------------------------------- collection
def page_title(md: str, fallback: str) -> str:
    for line in md.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return fallback.replace("-", " ").replace("_", " ").rsplit(".", 1)[0].capitalize()


def collect(docs_dir: str) -> tuple[list[dict], list[dict]]:
    found: dict[str, list[str]] = {}
    for dirpath, dirnames, filenames in os.walk(docs_dir):
        rel_dir = os.path.relpath(dirpath, docs_dir).replace(os.sep, "/")
        rel_dir = "" if rel_dir == "." else rel_dir
        top = rel_dir.split("/")[0]
        if top in EXCLUDE_DIRS:
            dirnames[:] = []
            continue
        dirnames.sort()
        for f in sorted(filenames):
            if f.endswith(".md"):
                found.setdefault(top, []).append(f"{rel_dir}/{f}" if rel_dir else f)

    known = [s for s, _ in SECTIONS]
    order = [s for s in known if s in found] + sorted(s for s in found if s not in known)
    titles = dict(SECTIONS)
    pages: list[dict] = []
    nav: list[dict] = []
    for section in order:
        preferred = PAGE_ORDER.get(section, [])

        def sort_key(path: str, section: str = section, preferred: list = preferred) -> tuple:
            rel = path[len(section) + 1:] if section else path
            depth = rel.count("/")
            name = rel.split("/")[-1]
            in_pref = rel in preferred
            return (depth, 0 if in_pref else 1, preferred.index(rel) if in_pref else 0, rel.lower())

        paths = sorted(found[section], key=sort_key)
        sec_title = titles.get(section, section.replace("-", " ").capitalize())
        for path in paths:
            with open(os.path.join(docs_dir, path), encoding="utf-8") as fh:
                raw = fh.read().replace("\r\n", "\n")
            rel = path[len(section) + 1:] if section else path
            group = None
            if "/" in rel:
                sub = rel.rsplit("/", 1)[0]
                group = GROUP_TITLES.get(sub.split("/")[-1], sub.split("/")[-1].replace("-", " ").capitalize())
            title = page_title(raw, os.path.basename(path))
            pages.append({"path": path, "title": title, "nav_title": "Start here" if path == "index.md" else title,
                          "section": sec_title, "group": group, "md": preprocess(raw)})
        nav.append({"title": sec_title, "pages": paths})
    return pages, nav


# --------------------------------------------------------------------------- build
def build_page() -> str:
    pages, nav = collect(DOCS)
    home = next((p for p in pages if p["path"] == "index.md"), None)
    title = home["title"] if home else "Project documentation"
    data = json.dumps({"title": title, "nav": nav, "pages": pages}, ensure_ascii=False, separators=(",", ":"))
    data = data.replace("</", "<\\/")  # valid JSON, cannot close the <script> tag

    def read(name: str) -> str:
        with open(os.path.join(VIEWER, name), encoding="utf-8") as fh:
            return fh.read()

    def js(name: str) -> str:
        return re.sub(r"</(script)", r"<\\/\1", read(os.path.join("vendor", name)), flags=re.I)

    values = {"TITLE": html.escape(title), "DATA": data, "MARKED": js("marked.min.js"), "MERMAID": js("mermaid.min.js")}
    template = read("viewer.html")
    out = re.sub(r"__(TITLE|DATA|MARKED|MERMAID)__", lambda m: values[m.group(1)], template)
    return out.replace("\r\n", "\n")


def read_text(path: str) -> str | None:
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def write_text(path: str, content: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(content)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if any generated file is out of date")
    args = ap.parse_args()

    # 1. Backlog page (a docs page itself, so it must be generated before the site).
    backlog_md = render_backlog.generate()
    if args.check:
        stale = [] if read_text(render_backlog.OUTPUT) == backlog_md else ["docs/backlog/index.md"]
    else:
        write_text(render_backlog.OUTPUT, backlog_md)

    # 2. Site.
    files = {"index.html": build_page(), "_headers": HEADERS, "robots.txt": ROBOTS}
    if args.check:
        stale += [f"docs-site/{n}" for n, c in files.items() if read_text(os.path.join(OUTPUT_DIR, n)) != c]
        if stale:
            print(f"Out of date: {', '.join(stale)}. Run: python .harness/scripts/build_docs.py")
            return 1
        print("Generated docs up to date")
        return 0
    for name, content in files.items():
        write_text(os.path.join(OUTPUT_DIR, name), content)
    size = len(files["index.html"]) // 1024
    print(f"written: docs/backlog/index.md, docs-site/ ({size} KB) - open docs-site/index.html")
    return 0


if __name__ == "__main__":
    sys.exit(main())
